import sys
import os
import asyncio
from langchain_core.runnables import RunnableConfig

# Ensure we can import app modules
sys.path.append(os.path.join(os.getcwd(), 'backend', 'app'))

from services.llm_service import get_monthly_weather_tool, node_tool_caller
from models.schemas import AgentState, LocationEntity

def run_tests():
    print("--- Test 1: Testing direct tool invocation with config ---")
    loc = LocationEntity(
        original_query="Tarlac City",
        resolved_name="Tarlac City",
        granularity="municipality_city",
        province="Tarlac",
        region="Region III",
        latitude=15.4802,
        longitude=120.5979,
        province_latitude=15.5,
        province_longitude=120.5
    )
    state = AgentState(
        user_query="What was the precipitation, soil moisture, and wind speed in Tarlac in 2023?",
        location=loc,
        active_action="GET_WEATHER_DATA",
        is_ready_for_tools=True
    )
    config = {"configurable": {"state": state}}
    
    # Try calling the tool directly
    try:
        res = get_monthly_weather_tool.invoke({"start_date": "2023-01-01", "end_date": "2023-12-31", "daily_vars": ["precipitation_sum", "invalid_var_123"]}, config=config)
        print("Tool returned:")
        print(res[:300] + "..." if len(res) > 300 else res)
    except Exception as e:
        print("Error:", e)

    print("\n--- Test 2: Testing node_tool_caller (LLM invocation) ---")
    try:
        new_state = node_tool_caller(state)
        messages = new_state.get("messages", [])
        if messages:
            last_msg = messages[-1]
            print("Tool Calls Generated by LLM:")
            print(last_msg.tool_calls)
        else:
            print("No messages generated.")
    except Exception as e:
        print("Error:", e)

run_tests()
